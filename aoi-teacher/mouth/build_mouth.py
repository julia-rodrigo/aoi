"""Aoi's lip-sync: a mouth track for every voice clip, worked out from the sound itself.

For each mp3 under ../audio (except the hum samples), the clip is decoded to 16 kHz mono and cut
into 50 ms frames (20 a second). Each frame gets a mouth shape from how loud it is and how bright
it sounds (spectral centroid):
  0 closed   quiet
  1 mid      soft speech
  2 open     loud, open vowels (a)
  3 o        loud but dark (o, u)
  4 smile    bright and not too loud (i, e, s)
Writes mouth.js: AOI_MOUTH["narr/abc.mp3"] = "0012342210...". Run it again after recording clips.
"""
import json, subprocess, sys
from pathlib import Path
import numpy as np

HERE = Path(__file__).resolve().parent
AUDIO = HERE.parent / 'audio'
SR, HOP = 16000, 800  # 50 ms frames

def track(path):
    raw = subprocess.run(['ffmpeg', '-v', 'error', '-i', str(path), '-ac', '1', '-ar', str(SR), '-f', 's16le', '-'],
                         capture_output=True, check=True).stdout
    x = np.frombuffer(raw, dtype=np.int16).astype(np.float32) / 32768.0
    n = len(x) // HOP
    if n == 0:
        return ''
    fr = x[:n * HOP].reshape(n, HOP)
    rms = np.sqrt((fr ** 2).mean(axis=1))
    win = np.hanning(HOP)
    spec = np.abs(np.fft.rfft(fr * win, axis=1))
    freqs = np.fft.rfftfreq(HOP, 1 / SR)
    cen = (spec * freqs).sum(axis=1) / (spec.sum(axis=1) + 1e-9)
    loud = rms / (np.percentile(rms, 95) + 1e-9)
    out = []
    for l, c in zip(loud, cen):
        if l < 0.14:
            s = '0'
        elif c > 2600 and l < 0.75:
            s = '4'
        elif l > 0.6:
            s = '3' if c < 1330 else '2'
        else:
            s = '1'
        out.append(s)
    # no one-frame flickers: a lone frame takes its neighbours' shape
    for i in range(1, len(out) - 1):
        if out[i - 1] == out[i + 1] != out[i]:
            out[i] = out[i - 1]
    return ''.join(out)

def main():
    data = {}
    for p in sorted(AUDIO.rglob('*.mp3')):
        rel = p.relative_to(AUDIO).as_posix()
        data[rel] = track(p)
    (HERE / 'mouth.js').write_text(
        '/* Generated by mouth/build_mouth.py: AOI_MOUTH[clip under audio/] = mouth shape per 50 ms\n'
        '   (0 closed, 1 mid, 2 open, 3 o, 4 smile), worked out from the recording. */\n'
        'var AOI_MOUTH = ' + json.dumps(data, separators=(',', ':')) + ';\n', encoding='utf-8')
    total = sum(len(v) for v in data.values())
    print(f'{len(data)} clips, {total / 20 / 60:.1f} minutes of mouth tracks, {(HERE / "mouth.js").stat().st_size // 1024} KB')

if __name__ == '__main__':
    main()
