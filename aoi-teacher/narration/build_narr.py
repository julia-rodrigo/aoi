"""Aoi's lesson narration, in her voice.

ja/*.tsv holds one line per lesson caption: <key> TAB <what Aoi says> (mostly Japanese, with
English words kept in English). The key is narrKey() from index.html: FNV-1a 32-bit over the
UTF-16 code units of the English caption with runs of whitespace collapsed and the ends trimmed.
lines_en.json (dumped from the app) lists every caption that should have a voice, so this
reports captions with no line yet and lines whose caption has changed or gone.

Writes clips.json for gen_narr.py, which records any clip not already in ../audio/narr/, and
narr.js (AOI_NARR[key] = [clip file, Japanese]) with the lines that are recorded; run it again
after recording.
"""
import hashlib, json, re, sys
from pathlib import Path

HERE = Path(__file__).resolve().parent

def narr_key(text):
    t = re.sub(r'\s+', ' ', text).strip()
    h = 0x811c9dc5
    b = t.encode('utf-16-le')
    for i in range(0, len(b), 2):
        h ^= b[i] | (b[i + 1] << 8)
        h = (h * 0x01000193) & 0xffffffff
    return '%08x' % h

def main():
    lines = json.loads((HERE / 'lines_en.json').read_text(encoding='utf-8'))
    want = {x['key']: x for x in lines}
    for x in lines:
        assert narr_key(x['text']) == x['key'], ('hash mismatch', x['text'])
    ja = {}
    for f in sorted((HERE / 'ja').glob('*.tsv')):
        for n, row in enumerate(f.read_text(encoding='utf-8').splitlines(), 1):
            if not row.strip() or row.startswith('#'):
                continue
            k, _, say = row.partition('\t')
            say = say.strip()
            if not re.fullmatch(r'[0-9a-f]{8}', k) or not say:
                sys.exit(f'{f.name}:{n}: bad row {row[:60]!r}')
            if k in ja:
                sys.exit(f'{f.name}:{n}: duplicate key {k}')
            ja[k] = say
    stale = [k for k in ja if k not in want]
    missing = [k for k in want if k not in ja]
    out, clips, unrecorded = {}, [], 0
    audio = HERE.parent / 'audio' / 'narr'
    for k, say in ja.items():
        if k in stale:
            continue
        clip = hashlib.sha1(say.encode('utf-8')).hexdigest()[:12] + '.mp3'
        clips.append({'file': clip, 'tts': say})
        if not (audio / clip).exists():
            unrecorded += 1  # only recorded lines go into the app
            continue
        out[k] = [clip, say]
    (HERE / 'narr.js').write_text(
        '/* Generated by build_narr.py: AOI_NARR[hash of English caption] = [clip in audio/narr/, what Aoi says]. */\n'
        'var AOI_NARR = ' + json.dumps(out, ensure_ascii=False, separators=(',', ':')) + ';\n', encoding='utf-8')
    (HERE / 'clips.json').write_text(json.dumps(clips, ensure_ascii=False, indent=0), encoding='utf-8')
    print(f'{len(out)} voiced lines in the app, {unrecorded} written but not recorded yet, '
          f'{len(missing)} captions still without a line, {len(stale)} stale lines')
    for k in stale:
        print('  stale:', k, ja[k][:40])

if __name__ == '__main__':
    main()
