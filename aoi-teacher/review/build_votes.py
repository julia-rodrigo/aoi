"""Bakes the votes from the shared web version into the app, so every update shows everyone's hearts.

1. Save the votes collection from the published artifact as JSON files (the ArtifactData tool's
   "list" with out_dir, collection "votes"), e.g. into /tmp/votes.
2. python3 review/build_votes.py /tmp/votes   -> writes feedback/votes.js

Only counts are kept (how many people loved each module, how many asked for more), never who.
"""
import datetime, json, sys
from pathlib import Path

src = Path(sys.argv[1])
likes, more, people = {}, {}, 0
for f in sorted(src.rglob('*.json')):
    d = json.loads(f.read_text(encoding='utf-8'))
    d = d.get('data', d)
    if not isinstance(d, dict):
        continue
    people += 1
    for k in set(d.get('likes', [])) | set(d.get('more', [])):
        likes[k] = likes.get(k, 0) + 1
    for k in set(d.get('more', [])):
        more[k] = more.get(k, 0) + 1
out = {'at': datetime.date.today().isoformat(), 'people': people, 'likes': likes, 'more': more}
dest = Path(__file__).resolve().parent.parent / 'feedback' / 'votes.js'
dest.write_text('/* Generated by review/build_votes.py from the votes saved on the shared web version, so app updates\n'
                '   show everyone\'s hearts. AOI_VOTES = {at, people, likes: {module key: people}, more: {...}}. */\n'
                'var AOI_VOTES = ' + json.dumps(out, ensure_ascii=False, separators=(',', ':')) + ';\n', encoding='utf-8')
print(f'{people} people, {len(likes)} loved modules, {len(more)} asked for more -> {dest}')
